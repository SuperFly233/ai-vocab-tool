import assert from 'node:assert/strict';
import '../scene-data.js';
const S=globalThis.SceneData;
const created='2026-10-19T00:00:00Z',later='2026-10-19T01:00:00Z';
const a={id:'one',title:'one',note:'my scene',createdAt:created,updatedAt:created};
const b={id:'two',title:'two',createdAt:created,updatedAt:later};
assert.equal(S.reconcile([a,b]).items.length,2);
assert.deepEqual(S.reconcile([a,b]),S.reconcile([b,a]));
assert.equal(S.reconcile([a],[{key:'one',deletedAt:later}]).items.length,0);
assert.equal(S.reconcile([{...a,updatedAt:'2026-10-19T02:00:00Z'}],[{key:'one',deletedAt:later}]).tombstones.length,0);
assert.equal(S.sourceUrl('javascript:alert(1)'), '');
assert.equal(S.sourceUrl('data:text/html,hello'), '');
assert.equal(S.sourceUrl('https://user:secret@example.com'), '');
assert.equal(S.sourceUrl('https://example.com/episode?t=123'),'https://example.com/episode?t=123');
assert.equal(S.normalizeScene({...a,media:[{id:'x',mime:'image/svg+xml',size:20}]}).media.length,0);
assert.equal(S.normalizeScene({...a,html:'<script>alert(1)</script>'}).html,undefined);
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a+yQAAAAASUVORK5CYII=','base64');
const file=new Blob([png],{type:'text/plain'});file.name='safe.png';
const inspected=await S.inspectFile(file);
assert.equal(inspected.ref.mime,'image/png');assert.ok(S.hashId(inspected.ref.id));
assert.equal(inspected.ref.id,(await S.inspectFile(file)).ref.id);
await assert.rejects(()=>S.inspectFile(new Blob(['<svg></svg>'],{type:'image/png'})));
assert.equal(S.detectMime(new Uint8Array(Buffer.from('GIF89a'))),'image/gif');
assert.equal(S.normalizeMedia([inspected.ref,inspected.ref]).length,1);
assert.equal(a.note,'my scene');
console.log('Scenes passed: merge/deletion/concurrency, URL and MIME safety, byte sniffing, hashing and deduplication.');
