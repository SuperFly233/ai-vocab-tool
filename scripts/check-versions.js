import assert from 'node:assert/strict';
await import('../history-data.js');
const {reconcileRolls,integrateResults}=globalThis.HistoryData;
const old='2026-01-01T00:00:00Z',now='2026-01-02T00:00:00Z',later='2026-01-03T00:00:00Z';
const a={headword:{title:'clock',coreMeaning:'notice'},senses:[{meaning:'notice',example:'A'}],collocations:[],confusions:[]};
const b={headword:{title:'CLOCK',coreMeaning:'time'},senses:[{example:'A',meaning:'notice'},{meaning:'measure time'}],collocations:[{phrase:'clock in'}],confusions:[{term:'watch'}]};
const rolls=[{id:'a',createdAt:old,result:a},{id:'b',createdAt:old,result:b}];
const deleted=[{key:'a',deletedAt:now}];
assert.deepEqual(reconcileRolls(rolls,deleted).rolls.map(r=>r.id),['b']);
assert.deepEqual(reconcileRolls([...rolls,...rolls].reverse(),deleted).rolls.map(r=>r.id),['b']);
const edit={...rolls[0],updatedAt:now,result:b};
assert.equal(reconcileRolls([rolls[0],edit]).rolls.length,1);
assert.deepEqual(reconcileRolls([edit,rolls[0]]),reconcileRolls([rolls[0],edit]));
const renamed={...rolls[0],name:'preferred',nameUpdatedAt:later};
const combined=reconcileRolls([edit,renamed]).rolls[0];
assert.deepEqual(combined.result,b);assert.equal(combined.name,'preferred','Concurrent naming must not discard edited content');
assert.deepEqual(reconcileRolls([edit,renamed]),reconcileRolls([renamed,edit]));
const restored=reconcileRolls([{...rolls[0],updatedAt:later}],deleted);
assert.equal(restored.rolls.length,1);assert.equal(restored.tombstones.length,0);
assert.equal(reconcileRolls(rolls,rolls.map(r=>({key:r.id,deletedAt:now}))).rolls.length,0,'Concurrent deletions must not synthesize a deleted version');
const before=JSON.stringify([a,b]);
const merged=integrateResults([a,b]);
assert.equal(merged.headword.coreMeaning,'notice');assert.equal(merged.senses.length,2);
assert.equal(merged.collocations.length,1);assert.equal(merged.confusions.length,1);
assert.equal(integrateResults([b,a]).headword.coreMeaning,'time');
merged.senses[0].meaning='edited';assert.equal(JSON.stringify([a,b]),before,'Integration must clone sources');
assert.throws(()=>integrateResults([]));
console.log('Version data passed: tombstones, stale edits, restore, concurrent deletion, base selection, exact union, source isolation.');
