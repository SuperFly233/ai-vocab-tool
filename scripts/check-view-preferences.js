import assert from 'node:assert/strict';
await import('../view-preferences.js');
const prefs=globalThis.ViewPreferences,older='2026-10-20T00:00:00.000Z',newer='2026-10-21T00:00:00.000Z';
const history={value:{sort:'updated',sortDir:'asc',filters:{language:['en']}},updatedAt:newer};
const scenes={value:{sort:'created',media:'video/'},updatedAt:older};
const merged=prefs.merge({history},{scenes});
assert.equal(prefs.get('history',{viewPreferences:merged}).sort,'updated');
assert.equal(prefs.get('scenes',{viewPreferences:merged}).sort,'created');
assert.deepEqual(prefs.merge({history},{scenes}),prefs.merge({scenes},{history}),'Different pages converge independently');
const sceneNew={value:{sort:'updated',study:'mastered'},updatedAt:newer};
assert.equal(prefs.merge({scenes},{scenes:sceneNew}).scenes.value.study,'mastered');
const changed=prefs.update('scenes',{sort:'created',query:'private search',source:'Story'}, {rememberViewFilters:true,viewPreferences:{history}});
assert.deepEqual(changed.viewPreferences.history,prefs.records({history}).history,'Scene edit cannot overwrite history');
assert.equal('query' in changed.viewPreferences.scenes.value,false,'Search text is never persisted');
assert.equal(prefs.get('scenes',{...changed,rememberViewFilters:false}).sort,'updated','Disabled memory restores defaults');
assert.equal(prefs.normalize('scenes',{sort:'wrong',media:'javascript:',study:'wrong'}).sort,'updated');
assert.equal(prefs.normalize('folders',{sort:'created',searchScope:'current',activeId:'private-folder'}).activeId,undefined);
const x={value:{sort:'created'},updatedAt:newer},y={value:{sort:'updated'},updatedAt:newer};
assert.deepEqual(prefs.merge({scenes:x},{scenes:y}),prefs.merge({scenes:y},{scenes:x}),'Equal clocks converge deterministically');
const restored=JSON.parse(JSON.stringify(changed));assert.deepEqual(prefs.get('scenes',restored),prefs.get('scenes',changed),'Backup/refresh preserves independent values');
console.log('View preferences: independent pages/clocks, deterministic cloud merge, refresh/backup, reset defaults, disabled memory and private query exclusion passed.');
